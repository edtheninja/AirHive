-- Persistent audit history for user-management operations.
CREATE TABLE user_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    actor_user_id BIGINT,
    target_user_id BIGINT,

    action VARCHAR(40) NOT NULL,
    previous_value VARCHAR(100),
    new_value VARCHAR(100),

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_audit_actor
        FOREIGN KEY (actor_user_id)
        REFERENCES app_users(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_user_audit_target
        FOREIGN KEY (target_user_id)
        REFERENCES app_users(id)
        ON DELETE SET NULL
);

CREATE INDEX idx_user_audit_actor
    ON user_audit_log(actor_user_id);

CREATE INDEX idx_user_audit_target
    ON user_audit_log(target_user_id);

CREATE INDEX idx_user_audit_created_at
    ON user_audit_log(created_at);